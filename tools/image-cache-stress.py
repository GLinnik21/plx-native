def image_jpeg(number):
    comment = f"PlxNative cache stress tile {number:05d}".encode()
    return JPEG[:2] + b"\xff\xfe" + struct.pack(">H", len(comment) + 2) + comment + JPEG[2:]


class Fixture:
    def __init__(self, count=1200, access_log=None):
        if not 1001 <= count <= 10000:
            raise ValueError("tile count must be between 1001 and 10000")
        self.count = count
        self.phase = "cold"
        self.images = True
        self.lock = threading.Lock()
        self.log = open(access_log, "x", encoding="utf-8") if access_log else None
        self.records = []
        self.started = time.monotonic()

    def close(self):
        if self.log:
            self.log.close()

    def record(self, kind, path, status, size, **fields):
        with self.lock:
            row = dict(at_s=round(time.monotonic() - self.started, 3), phase=self.phase,
                       kind=kind, path=path, status=status, bytes=size, **fields)
            self.records.append(row)
            if self.log:
                self.log.write(json.dumps(row, sort_keys=True) + "\n")
                self.log.flush()

    def snapshot(self):
        with self.lock:
            return dict(tiles=self.count, machine_id=MACHINE_ID, phase=self.phase,
                        images=self.images, phases=access_summary(self.records))

    def control(self, body):
        if not isinstance(body, dict) or set(body) - {"phase", "images"}:
            raise ValueError("only phase and images are accepted")
        phase = body.get("phase", self.phase)
        enabled = body.get("images", self.images)
        if not isinstance(phase, str) or not re.fullmatch(r"[a-zA-Z0-9_-]{1,40}", phase):
            raise ValueError("phase must be 1-40 letters, digits, underscores or hyphens")
        if not isinstance(enabled, bool):
            raise ValueError("images must be a boolean")
        with self.lock:
            self.phase, self.images = phase, enabled

    def item(self, number):
        return dict(ratingKey=str(number), key=f"/library/metadata/{number}", type="movie",
                    title=f"Tile {number:04d}", titleSort=f"Tile {number:04d}", year=2026,
                    thumb=f"/library/metadata/{number}/thumb/1", librarySectionID=1,
                    librarySectionTitle="Image cache stress", duration=6000000,
                    addedAt=1700000000 + number, updatedAt=1700000000)

    def metadata(self, path, query):
        if path in ("/", "/identity"):
            return dict(machineIdentifier=MACHINE_ID, friendlyName="Image cache stress",
                        version="1.43.3.0", myPlexSubscription=False)
        if path in ("/library/sections", "/library/sections/all"):
            return dict(size=1, Directory=[dict(key="1", type="movie", title="Image cache stress")])
        if path == "/library/sections/1/all":
            start = int(query.get("X-Plex-Container-Start", ["0"])[0])
            size = int(query.get("X-Plex-Container-Size", ["60"])[0])
            if start < 0 or not 0 <= size <= 10000:
                raise ValueError("invalid page range")
            end = min(start + size, self.count)
            items = [self.item(i + 1) for i in range(start, end)]
            return dict(size=len(items), totalSize=self.count, offset=start, Metadata=items,
                        Meta={"Type": [{"active": True, "Sort": [
                            {"key": "titleSort", "title": "Title", "defaultDirection": "asc"}]}]})
        if path == "/library/sections/1/firstCharacter":
            return dict(size=1, Directory=[dict(key="T", title="T", size=self.count)])
        if path == "/library/sections/1/genre":
            return dict(size=0, Directory=[])
        if path in ("/hubs", "/hubs/sections/1", "/hubs/continueWatching"):
            return dict(size=0, Hub=[], Metadata=[])
        match = re.fullmatch(r"/library/metadata/([1-9][0-9]*)", path)
        if match and 1 <= int(match[1]) <= self.count:
            return dict(size=1, Metadata=[self.item(int(match[1]))])
        return None


def handler(fixture):
    class Handler(http.server.BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"

        def log_message(self, _format, *_args):
            pass  # BaseHTTPRequestHandler would print the token-bearing request.

        def send_body(self, status, content_type, data):
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            try:
                self.wfile.write(data)
            except (BrokenPipeError, ConnectionResetError):
                pass

        def send_json(self, status, obj):
            data = json.dumps(obj, separators=(",", ":")).encode()
            self.send_body(status, "application/json", data)
            return len(data)

        def do_POST(self):
            if self.path != "/__stress/control" or self.client_address[0] not in ("127.0.0.1", "::1"):
                self.send_json(403, {"error": "control is loopback-only"})
                return
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if not 0 < length <= 1024:
                    raise ValueError("invalid control body length")
                fixture.control(json.loads(self.rfile.read(length)))
            except (ValueError, UnicodeError) as error:
                self.send_json(400, {"error": str(error)})
                return
            self.send_json(200, fixture.snapshot())

        def do_GET(self):
            parsed = urllib.parse.urlsplit(self.path)
            path = parsed.path
            query = urllib.parse.parse_qs(parsed.query)
            if path == "/__stress/stats":
                self.send_json(200, fixture.snapshot())
                return
            if path == "/photo/:/transcode":
                source = query.get("url", [""])[0]
                match = THUMB.fullmatch(source)
                try:
                    width = int(query.get("width", ["250"])[0])
                    height = int(query.get("height", ["375"])[0])
                    if not (match and int(match[1]) <= fixture.count and
                            1 <= width <= 1920 and 1 <= height <= 1080):
                        raise ValueError("invalid fixture image")
                except ValueError:
                    self.send_json(400, {"error": "invalid fixture image"})
                    fixture.record("invalid_image", path, 400, 0)
                    return
                with fixture.lock:
                    enabled = fixture.images
                status = 200 if enabled else 503
                data = image_jpeg(int(match[1])) if enabled else b"images disabled"
                self.send_body(status, "image/jpeg" if enabled else "text/plain", data)
                # The canonical key excludes auth and includes every transform the app uses.
                key = f"{source}|{width}x{height}|{query.get('format', ['jpeg'])[0]}|minSize={query.get('minSize', [''])[0]}"
                fixture.record("image", source, status, len(data), image_id=int(match[1]), key=key)
                return
            try:
                response = fixture.metadata(path, query)
            except ValueError:
                response = None
            status = 200 if response is not None else 404
            size = self.send_json(status, {"MediaContainer": response} if response is not None
                                  else {"error": "unknown fixture endpoint"})
            fields = {"start": response["offset"], "count": response["size"]} if response and "offset" in response else {}
            fixture.record("metadata", path, status, size, **fields)
    return Handler


def access_summary(records):
    phases = {}
    for phase in sorted({row["phase"] for row in records}):
        selected = [row for row in records if row["phase"] == phase]
        images = [row for row in selected if row["kind"] == "image"]
        success = [row for row in images if row["status"] == 200]
        pages = [row for row in selected if "start" in row]
        phases[phase] = dict(image_requests=len(images), image_successes=len(success),
            image_failures=len(images) - len(success),
            unique_image_keys=len({row["key"] for row in success}),
            unique_image_ids=len({row["image_id"] for row in success}),
            image_bytes=sum(row["bytes"] for row in success),
            metadata_requests=sum(row["kind"] == "metadata" for row in selected),
            unique_listing_items=len({i for row in pages for i in range(row["start"], row["start"] + row["count"])}),
            duration_s=round(selected[-1]["at_s"] - selected[0]["at_s"], 3))
    return phases


def quantiles(values):
    if not values:
        return {"n": 0}
    ordered = sorted(values)
    return dict(n=len(values), min=ordered[0], p10=ordered[math.floor((len(ordered)-1)*.10)],
                p50=ordered[math.floor((len(ordered)-1)*.50)],
                p95=ordered[math.floor((len(ordered)-1)*.95)], max=ordered[-1])


def event_summary(path):
    lines = Path(path).read_text().splitlines()
    metrics = [dict((key, int(value)) for key, value in re.findall(r"([a-z_]+)=([0-9]+)", match[1]))
               for line in lines if (match := CACHE.search(line))]
    frames, worst, intervals, slow, window_slow = [], [], [], [], []
    for line in lines:
        if line.startswith("FRAMEDROP ") and "route=library" in line:
            window_slow.append({key: float(value) for key, value in
                re.findall(r"(total|ingest|results|tick_drain|navcommit|prepare|draw|capture|swap|up)=([0-9.]+)", line)})
        match = FPS.search(line)
        if not match:
            continue
        frames.append((int(match[1]), int(match[2])))
        # Close complete heartbeat windows only; startup and the unfinished final window
        # cannot inflate or dilute steady-state frame-drop frequencies.
        if len(frames) > 5:
            slow.extend(window_slow)
            if peak := WORST.search(line):
                worst.append(float(peak[1]))
            fields = {key: float(value) for key, value in
                      re.findall(r"(frame_[a-z0-9]+)=([0-9.]+)", line)}
            if fields.get("frame_n", 0):
                intervals.append(fields)
        window_slow = []
    pacing = {key: int(sum(row.get("frame_" + key, 0) for row in intervals))
              for key in ("n", "gt16", "gt33", "gt50", "gt100")}
    pacing.update(max_ms=max((row.get("frame_max", 0) for row in intervals), default=0),
        worst_window_p95_ms=max((row.get("frame_p95", 0) for row in intervals), default=0),
        worst_window_p99_ms=max((row.get("frame_p99", 0) for row in intervals), default=0))
    pacing["over_33ms_percent"] = round(100 * pacing["gt33"] / pacing["n"], 3) if pacing["n"] else None
    # These are over-threshold CPU work samples, not an uncensored frame-time distribution.
    work = dict(recorded_slow_frames=len(slow),
        with_image_upload=sum(row.get("up", 0) > 0 for row in slow),
        over_33ms=sum(row["total"] > 1000 / 30 for row in slow),
        over_50ms=sum(row["total"] > 50 for row in slow),
        over_100ms=sum(row["total"] > 100 for row in slow),
        worst_frames=sorted(slow, key=lambda row: row["total"], reverse=True)[:5])
    return dict(cache=metrics[-1] if metrics else {}, cache_samples=len(metrics),
                library_samples=len(frames), loop=quantiles([value[0] for value in frames[5:]]),
                fps=quantiles([value[1] for value in frames[5:]]), worstframe_ms=quantiles(worst),
                pacing=pacing, slow_cpu_work=work,
                invalid_pacing=any(re.search(r"\bsim=1\b|\brec=\d+us\b|(?:GPU|CPU)PROF|HWCNT", line) for line in lines))


def memory_summary(path):
    rows = read_jsonl(path)
    return dict(rss_kib=quantiles([row["rss_kib"] for row in rows]),
                hwm_kib=max((row.get("hwm_kib", row["rss_kib"]) for row in rows), default=0),
                growth_kib=rows[-1]["rss_kib"] - rows[0]["rss_kib"] if rows else 0)


def read_jsonl(path):
    return [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]


def grade(access, cold, warm, minimum=1001, seconds=90):
    errors = []
    cold_net, warm_net = access.get("cold", {}), access.get("warm", {})
    if cold_net.get("unique_image_ids", 0) < minimum:
        errors.append(f"cold run did not fetch {minimum} distinct tile images")
    if cold_net.get("image_failures", 0):
        errors.append("cold run had image request failures")
    if warm_net.get("unique_listing_items", 0) < minimum:
        errors.append(f"warm run did not page through {minimum} distinct listing items")
    if warm_net.get("image_requests", 0):
        errors.append("warm process restart requested image bytes from the server")
    for name, leg in (("cold", cold), ("warm", warm)):
        if leg["library_samples"] < seconds:
            errors.append(f"{name} run has fewer than {seconds} Library heartbeat samples")
        if leg["invalid_pacing"]:
            errors.append(f"{name} run was a simulator, recorder or profiler run")
        if leg.get("pacing", {}).get("n", 0) < 1000:
            errors.append(f"{name} run lacks frame interval/drop evidence")
        if leg["cache"].get("entries", 0) < minimum or leg["cache"].get("bytes", 0) <= 0:
            errors.append(f"{name} run has insufficient disk-cache entries/bytes evidence")
    if cold["cache"].get("writes", 0) < minimum:
        errors.append("cold run did not write the distinct images into the cache")
    if cold["cache"].get("fetches", 0) < minimum:
        errors.append("cold run did not report the distinct network image fetches")
    if warm["cache"].get("hits", 0) < minimum:
        errors.append("warm process did not read enough images from disk")
    if warm["cache"].get("fetches") != 0:
        errors.append("warm process did not report zero image fetches")
    return errors


def grade_baseline(access, baseline, minimum=1001, seconds=90):
    errors = []
    if baseline["invalid_pacing"] or baseline["pacing"]["n"] < 1000 or baseline["library_samples"] < seconds:
        errors.append("RAM-only baseline lacks valid frame interval/drop evidence")
    cache = baseline["cache"]
    if any(cache.get(key, -1) != 0 for key in ("hits", "writes", "entries")):
        errors.append("RAM-only baseline did not bypass the disk cache")
    if access.get("baseline", {}).get("unique_image_ids", 0) < minimum or cache.get("fetches", 0) < minimum:
        errors.append("RAM-only baseline did not load the distinct tile images")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    serve = sub.add_parser("serve", help="serve a synthetic PMS; does not drive the TV")
    serve.add_argument("--bind", default="0.0.0.0")
    serve.add_argument("--port", type=int, default=8027)
    serve.add_argument("--count", type=int, default=1200)
    serve.add_argument("--access-log", required=True, help="new JSONL file; refuses overwriting evidence")
    control = sub.add_parser("control", help="label the next leg and enable/disable images")
    control.add_argument("--port", type=int, default=8027)
    control.add_argument("--phase", required=True)
    control.add_argument("--images", choices=("on", "off"), required=True)
    report = sub.add_parser("report", help="grade cold and warm evidence; emits sanitized JSON")
    report.add_argument("--access-log", required=True)
    report.add_argument("--cold-events", required=True)
    report.add_argument("--warm-events", required=True)
    report.add_argument("--baseline-events", help="optional RAM-only control run (imagecache-bypass)")
    report.add_argument("--baseline-memory")
    report.add_argument("--cold-memory")
    report.add_argument("--warm-memory")
    report.add_argument("--min-unique", type=int, default=1001)
    report.add_argument("--min-seconds", type=int, default=90)
    args = parser.parse_args()
    if args.command == "report" and (args.min_unique < 1001 or args.min_seconds < 90):
        parser.error("stress grading requires at least 1001 unique images and 90 seconds per leg")
    if args.command == "serve":
        fixture = Fixture(args.count, args.access_log)
        server = http.server.ThreadingHTTPServer((args.bind, args.port), handler(fixture))
        print(json.dumps(dict(listening=server.server_address, tiles=args.count, machine_id=MACHINE_ID)), flush=True)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass
        finally:
            server.server_close()
            fixture.close()
    elif args.command == "control":
        request = urllib.request.Request(f"http://127.0.0.1:{args.port}/__stress/control",
            data=json.dumps(dict(phase=args.phase, images=args.images == "on")).encode(),
            headers={"Content-Type": "application/json"}, method="POST")
        with urllib.request.urlopen(request, timeout=10) as response:
            print(json.dumps(json.load(response), indent=2, sort_keys=True))
    else:
        access = access_summary(read_jsonl(args.access_log))
        cold, warm = event_summary(args.cold_events), event_summary(args.warm_events)
        errors = grade(access, cold, warm, args.min_unique, args.min_seconds)
        for name, path, result in (("cold", args.cold_memory, cold), ("warm", args.warm_memory, warm)):
            if path:
                result["memory"] = memory_summary(path)
        result = dict(passed=not errors, errors=errors, access=access, cold=cold, warm=warm)
        if args.baseline_events:
            baseline = event_summary(args.baseline_events)
            if args.baseline_memory:
                baseline["memory"] = memory_summary(args.baseline_memory)
            result["baseline"] = baseline
            errors.extend(grade_baseline(access, baseline, args.min_unique, args.min_seconds))
            result["passed"] = not errors
        print(json.dumps(result, indent=2, sort_keys=True))
        return int(bool(errors))
    return 0


