#[test]
fn the_pins_run_against_an_idle_playhead() {
    let _g = plx_base::testlock::serial();
    assert_idle_playhead();
    // and the same state, read the other way: a fresh page is hidden, on the scrubber, with the
    // row's first button selected, and asks for nothing
    let mut run = Run::boot(Occupant::Plain);
    let seen = run.seen();
    assert_eq!((seen.region, seen.btn, seen.tab), (0, 0, 0));
    assert_eq!((seen.flags.as_str(), seen.reqs.as_str(), seen.scrub_ns), ("-", "", -1));
}

/// One test per state of the row, so a failure names the occupant that moved.
macro_rules! walks {
    ($($test:ident: $name:expr, $occupant:expr, $chapters:expr, $table:ident;)*) => {$(
        #[test]
        fn $test() {
            let _g = plx_base::testlock::serial();
            check_case(&Case { name: $name, occupant: $occupant, chapters: $chapters, pins: $table });
        }
    )*};
}

