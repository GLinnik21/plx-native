/// The longest key string any pin replays. Past it the clock this harness runs (600 ms a press)
/// would reach the transport's own timeout and the Up Next countdown, and a pin would start to
/// grade the timeouts rather than the keys.
const DEEPEST: usize = 8;

// ---- the harness -----------------------------------------------------------------------------

/// The focus region as a number, whichever type `HudNav::focus` has: `i32` today, `GroupId` after
/// the split. The two spell the same three places (scrubber 0, control row 1, tabs 2).
trait Region {
    fn region(&self) -> u32;
}
impl Region for i32 {
    fn region(&self) -> u32 {
        *self as u32
    }
}
impl Region for GroupId {
    fn region(&self) -> u32 {
        self.0
    }
}

/// Who occupies the control row, built only through the public constructors.
#[derive(Clone, Copy, Debug)]
enum Occupant {
    /// the ordinary Subtitles, Audio and More discs (a film)
    Plain,
    /// an episode with a neighbour on both sides: Previous and Next join the row
    Episode,
    /// the first episode of a show: only Next joins
    NextOnly,
    /// the last episode of a show: only Previous joins
    PreviousOnly,
    /// a Skip Intro pill
    SkipIntro,
    /// a Skip Credits pill (a credits segment that does not run to the end)
    SkipCredits,
    /// Watch Credits + Next Episode
    UpNext,
}

fn marker(kind: plx_data::metadata::MarkerKind, final_seg: bool) -> plx_data::metadata::Marker {
    plx_data::metadata::Marker { kind, start_ms: 10_000, end_ms: 40_000, final_seg }
}

fn slot_of(occupant: Occupant) -> ControlSlot {
    use plx_data::metadata::MarkerKind::{Credits, Intro};
    use plx_media::route::NextEpisodeMode::Countdown;
    let discs = |previous, next| ControlSlot::Discs(Controls { previous, next, restart: false });
    let slot = match occupant {
        Occupant::Plain => ControlSlot::Discs(Controls::NONE),
        Occupant::Episode => discs(true, true),
        Occupant::NextOnly => discs(false, true),
        Occupant::PreviousOnly => discs(true, false),
        Occupant::SkipIntro => slot_for(Some(marker(Intro, false)), false, Countdown),
        Occupant::SkipCredits => slot_for(Some(marker(Credits, false)), false, Countdown),
        Occupant::UpNext => slot_for(Some(marker(Credits, true)), true, Countdown),
    };
    // the constructors above are the claim; check the variant each one built
    let built = match occupant {
        Occupant::Plain | Occupant::Episode | Occupant::NextOnly | Occupant::PreviousOnly => {
            matches!(slot, ControlSlot::Discs(_))
        }
        Occupant::SkipIntro | Occupant::SkipCredits => matches!(slot, ControlSlot::Skip(_)),
        Occupant::UpNext => matches!(slot, ControlSlot::UpNext(_)),
    };
    assert!(built, "{occupant:?} built the wrong occupant");
    slot
}

/// The idle playhead every pin assumes. Reading these is how the pins hold the premise: another
/// module that leaked a duration, a pause or a busy pipeline would otherwise surface as a
/// mismatching table row that looks like a behaviour change.
fn assert_idle_playhead() {
    use std::sync::atomic::Ordering::Relaxed;
    assert_eq!(plx_media::player::SHARED.duration_ns.load(Relaxed), 0, "a leaked duration");
    assert!(!plx_media::player::TX.paused.load(Relaxed), "a leaked pause");
    let ps = plx_media::route::idle_session_for_test();
    assert!(!plx_media::player::loading(ps), "a busy pipeline");
    assert_ne!(
        plx_media::route::instant_dpad_seeking(),
        plx_plex::plex::session::InstantDpadSeeking::On,
        "instant D-pad seeking changes what LEFT and RIGHT do on a hidden transport",
    );
}

/// Mounts the player screen for the one page the dispatcher opens.
struct PinMounter;
impl Mounter<TestHost> for PinMounter {
    fn mount(
        &mut self,
        _id: InstanceId,
        _arg: &FixtureArg,
        _ret: &ReturnState<u32, PageMemory>,
        cx: &Cx<'_, TestHost>,
        _fx: &mut Effects<'_, TestHost>,
    ) -> Box<dyn Screen<TestHost>> {
        let InputOwner::Entry(entry) = cx.owner else { panic!("the page owns its own input") };
        Box::new(PlayerScreen::new(entry, plx_appkit::player_hud::loaded::classic_for_test()))
    }
}

/// The application's side of the frame, reduced to recording what the player asked for.
struct PinRig {
    mounter: PinMounter,
    measure: FixtureMeasure,
    reqs: Vec<PlayerReq>,
}
impl Rig<TestHost> for PinRig {
    fn split(&mut self) -> Split<'_, TestHost> {
        Split { mounter: &mut self.mounter, views: (), measure: &self.measure }
    }
    fn deliver(&mut self, _: MachineId, _: &AppMsg, _: &CxParts<u32>, _: &mut Effects<'_, TestHost>) -> Handled {
        Handled::No
    }
    fn timer(&mut self, _: MachineId, _: TimerId, _: &CxParts<u32>, _: &mut Effects<'_, TestHost>) {}
    fn app_fx(&mut self, _: MachineId, effect: AppFx, _: &CxParts<u32>, _: &mut Effects<'_, TestHost>) {
        if let AppFx::Player(req) = effect {
            self.reqs.push(req);
        }
    }
    fn log(&mut self, _: &str) {}
    fn prepare(&mut self, _: &mut Budget, _: &mut Present) {}
    fn ls2_pump(&mut self) {}
    fn opaque_route(&mut self, _: bool) {}
    fn clear_opaque_region(&mut self) {}
    fn now_us(&self) -> u64 {
        0
    }
}

/// One pinned step: the keys pressed from a fresh page, and what the screen shows after the last.
struct Pin {
    keys: &'static str,
    region: u32,
    btn: i32,
    tab: i32,
    /// `v` visible when the last key arrived, `r` the last key raised the transport's timer,
    /// `d` dismissed; `-` for none
    flags: &'static str,
    /// the `PlayerReq`s the last key raised, space-separated, as `Debug` prints them
    reqs: &'static str,
}

const fn p(keys: &'static str, region: u32, btn: i32, tab: i32, flags: &'static str, reqs: &'static str) -> Pin {
    Pin { keys, region, btn, tab, flags, reqs }
}

/// Everything one step is graded on.
#[derive(Clone, Debug, PartialEq)]
struct Seen {
    region: u32,
    btn: i32,
    tab: i32,
    flags: String,
    reqs: String,
    /// `-1` while no scrub is under way, which is all the idle playhead can produce
    scrub_ns: i64,
}

impl Seen {
    /// The table row that records this observation, in the table's own notation.
    fn line(&self, keys: &str) -> String {
        format!(
            "p(\"{keys}\", {}, {}, {}, \"{}\", \"{}\"),",
            self.region, self.btn, self.tab, self.flags, self.reqs
        )
    }

    fn is(&self, pin: &Pin) -> bool {
        self.region == pin.region
            && self.btn == pin.btn
            && self.tab == pin.tab
            && self.flags == pin.flags
            && self.reqs == pin.reqs
            && self.scrub_ns == -1
    }
}

/// One mounted player page in a real dispatcher.
struct Run {
    d: Dispatcher<TestHost>,
    rig: PinRig,
    id: EntryId,
    now: u32,
    raised: bool,
}

impl Run {
    fn boot(occupant: Occupant) -> Run {
        let mut d: Dispatcher<TestHost> = Dispatcher::new();
        let mut rig = PinRig { mounter: PinMounter, measure: FixtureMeasure, reqs: Vec::new() };
        d.request(MachineId::Nav, NavOp::Root(FixtureArg::VideoPlane));
        d.frame_with(&mut rig, tick(0), vec![], vec![], &mut NoTap, false);
        let id = d.nav.top_page().expect("the player page mounted").id;
        let mut run = Run { d, rig, id, now: 1_000, raised: false };
        run.screen().slot = slot_of(occupant);
        run.frame(16, vec![]);
        run.rig.reqs.clear();
        run
    }

    fn screen(&mut self) -> &mut PlayerScreen {
        let id = self.id;
        self.d
            .nav
            .entry_mut(id)
            .and_then(|entry| entry.inst.as_mut())
            .and_then(|inst| inst.screen.as_any_mut())
            .and_then(|any| any.downcast_mut::<PlayerScreen>())
            .expect("the mounted page is the player")
    }

    fn frame(&mut self, ms: u32, inputs: Vec<InputEvent<u32>>) {
        self.d.frame_with(&mut self.rig, tick(ms), inputs, vec![], &mut NoTap, false);
    }

    /// The frames after a key or a swap that have nothing in them: the Tick-time repair, then
    /// enough time for a press armed on key-down to be released, dip and commit.
    fn settle(&mut self, from: u32) {
        for after in [144, 192, 240, 288, 336, 400] {
            self.frame(from + after, vec![]);
        }
    }

    /// One bound key as the television delivers it.
    fn press(&mut self, k: Key) {
        let now = self.now;
        let ps = plx_media::route::idle_session_for_test();
        // the app's per-key preamble, before the key-down frame
        self.screen().hud.note_fresh_press(ps, now, false);
        self.frame(now, vec![key(k, tick(now))]);
        self.frame(now + 16, vec![]);
        self.frame(now + 112, vec![key_up(k, tick(now + 112))]);
        self.settle(now);
        self.now += 600;
    }

    /// The app pushes plain discs into the screen, as its per-frame slot push does when a
    /// stand-in or an episode neighbour goes away.
    fn push_plain_discs(&mut self) {
        let now = self.now;
        self.screen().slot = ControlSlot::Discs(Controls::NONE);
        self.frame(now, vec![]);
        self.settle(now);
        self.now += 600;
    }

    fn step(&mut self, c: char) {
        // what a step raised is what the LAST key raised, not the walk so far
        self.rig.reqs.clear();
        let before = self.screen().hud.until;
        match c {
            'U' => self.press(Key::Up),
            'D' => self.press(Key::Down),
            'L' => self.press(Key::Left),
            'R' => self.press(Key::Right),
            'K' => self.press(Key::Ok),
            '!' => self.push_plain_discs(),
            other => panic!("no such step {other:?}"),
        }
        self.raised = self.screen().hud.until > before;
    }

    fn walk(&mut self, keys: &str) {
        assert!(keys.chars().count() <= DEEPEST, "\"{keys}\" is longer than a pin may be");
        for c in keys.chars() {
            self.step(c);
        }
    }

    fn seen(&mut self) -> Seen {
        let reqs = std::mem::take(&mut self.rig.reqs)
            .iter()
            .map(|r| format!("{r:?}"))
            .collect::<Vec<_>>()
            .join(" ");
        let raised = self.raised;
        let s = self.screen();
        let mut flags = String::new();
        if s.hud.visible_at_press {
            flags.push('v');
        }
        if raised {
            flags.push('r');
        }
        if s.hud.dismissed {
            flags.push('d');
        }
        if flags.is_empty() {
            flags.push('-');
        }
        Seen {
            region: s.hud.nav.focus.region(),
            btn: s.hud.nav.btn,
            tab: s.hud.nav.tab,
            flags,
            reqs,
            scrub_ns: s.scrub.ns,
        }
    }
}

/// A playing item with two chapters, installed in the test thread's metadata store and removed
/// again on drop: the tabs row has a second tab only while the item has chapters.
struct Chaptered;
impl Chaptered {
    fn install() -> Chaptered {
        let chapter = |index: i64| plx_data::metadata::Chapter {
            index,
            start_ms: index * 60_000,
            title: format!("Chapter {index}"),
            thumb: String::new(),
        };
        assert!(test_store().run(plx_data::stores::metadata::MetadataCmd::InstallPlaying(Some(
            plx_data::metadata::PlayingItem {
                sid: plx_plex::plex::ServerId::from_raw(0),
                rk: "rk".into(),
                show_rk: String::new(),
                kind: String::new(),
                audio: Vec::new(),
                subs: Vec::new(),
                video_fps: 0.0,
                width: 0,
                height: 0,
                bitrate: 0,
                dovi: Default::default(),
                markers: Vec::new(),
                chapters: vec![chapter(1), chapter(2)],
                hdr: false,
            }
        ))));
        Chaptered
    }
}
impl Drop for Chaptered {
    fn drop(&mut self) {
        let _ = test_store().run(plx_data::stores::metadata::MetadataCmd::InstallPlaying(None));
    }
}

/// A table of pins for one state of the row.
struct Case {
    name: &'static str,
    occupant: Occupant,
    /// whether the playing item has chapters (a second tab)
    chapters: bool,
    pins: &'static [Pin],
}

/// Replay every pin of a case from a fresh page and compare the state after its last key.
fn check_case(case: &Case) {
    assert_idle_playhead();
    let _chapters = case.chapters.then(Chaptered::install);
    for pin in case.pins {
        let mut run = Run::boot(case.occupant);
        run.walk(pin.keys);
        let got = run.seen();
        assert!(
            got.is(pin),
            "{} ({:?}, chapters={}) after \"{}\":\n  expected {}\n  actual   {}",
            case.name,
            case.occupant,
            case.chapters,
            pin.keys,
            Seen {
                region: pin.region,
                btn: pin.btn,
                tab: pin.tab,
                flags: pin.flags.into(),
                reqs: pin.reqs.into(),
                scrub_ns: -1
            }
            .line(pin.keys),
            got.line(pin.keys),
        );
    }
}

// ---- the geometry census ---------------------------------------------------------------------

type Ext = (f32, f32, f32, f32);

fn ext(r: plx_ui::Rect) -> Ext {
    (r.x, r.y, r.w, r.h)
}

/// A thousandth of a pixel: far below anything a panel can show, wide enough that the same
/// constants combined in another order cannot trip a pin.
fn near(a: Ext, b: Ext) -> bool {
    [(a.0, b.0), (a.1, b.1), (a.2, b.2), (a.3, b.3)].iter().all(|(x, y)| (x - y).abs() < 1e-3)
}

/// The elements every census probes: each range's first and last stop (the control range's last
/// probe is its tenth element), the gaps between the ranges, and one past each end, so a re-addressing shows up as a changed row.
const PROBES: [u32; 22] = [
    0, 1, 9, CONTROL, CONTROL + 1, CONTROL + 2, CONTROL + 3, CONTROL + 4, CONTROL + 5, CONTROL + 9, 20, 21, 22, 29,
    30, 31, 32, 33, 34, 35, 40_000, 40_001,
];

/// The first control's element. The control row's own range, open-ended above this, sits clear of
/// the tabs (20), the failure read-out (30) and the repair card (40 000), so the row can hold any
/// number of controls (it was ten, `10..20`, before the element ranges were re-cut for control
/// identity).
const CONTROL: u32 = 0x1_0000;

/// What the screen reports for one state of the row: its groups, and the group and placement of
/// every probed element.
struct Census {
    name: &'static str,
    occupant: Occupant,
    chapters: bool,
    failed: bool,
    /// (group id, length, extent), in the order the screen declares them: the pointer's z-order
    groups: &'static [(u32, usize, Ext)],
    /// (element, its group, its rect), one per entry of [`PROBES`], in order
    places: &'static [(u32, Option<u32>, Option<Ext>)],
}

fn census_screen(occupant: Occupant, failed: bool) -> PlayerScreen {
    let mut screen = PlayerScreen::new(ENTRY, plx_appkit::player_hud::loaded::classic_for_test());
    screen.slot = slot_of(occupant);
    if failed {
        screen.busy = Busy::Readout(
            plx_ui::widgets::StatusKind::Failed,
            core::ffi::CStr::from_bytes_with_nul(b"failed\0").unwrap(),
        );
    }
    screen
}

fn check_census(case: &Census) {
    assert_idle_playhead();
    let _chapters = case.chapters.then(Chaptered::install);
    let screen = census_screen(case.occupant, case.failed);
    let cx: Cx<'static, TestHost> = super::cx();
    let mut groups: Vec<GroupSpec> = Vec::new();
    Focusable::<TestHost>::groups(&screen, &cx, &mut groups);
    let ids: Vec<u32> = groups.iter().map(|g| g.id.0).collect();
    let want_ids: Vec<u32> = case.groups.iter().map(|g| g.0).collect();
    assert_eq!(ids, want_ids, "{}: the groups declared, in z-order", case.name);
    for (got, want) in groups.iter().zip(case.groups) {
        assert!(
            got.len == want.1 && near(ext(got.extent), want.2),
            "{}: group {} expected (len {}, extent {:?}), got (len {}, extent {:?})",
            case.name, want.0, want.1, want.2, got.len, ext(got.extent),
        );
    }
    let tabled: Vec<u32> = case.places.iter().map(|p| p.0).collect();
    assert_eq!(tabled, PROBES, "{}: the table must hold every probe, in order", case.name);
    for &(elem, group, rect) in case.places {
        let in_group = Focusable::<TestHost>::group_of(&screen, &elem, &cx).map(|g| g.0);
        assert_eq!(in_group, group, "{}: element {elem}'s group", case.name);
        let placed = Focusable::<TestHost>::place(&screen, &elem, &cx, At::Drawn);
        match (placed, rect) {
            (None, None) => {}
            (Some(got), Some(want)) => {
                assert!(
                    near(ext(got.rect), want),
                    "{}: element {elem} expected {want:?}, got {:?}",
                    case.name, ext(got.rect),
                );
                // a transport element's resting rect is its drawn rect, it is never clipped and
                // it is not an indexed card
                assert_eq!(got.rest_rect, got.rect, "{}: element {elem}'s rest rect", case.name);
                assert_eq!(got.clip, plx_ui::Rect::FULL, "{}: element {elem}'s clip", case.name);
                assert_eq!(got.index, None, "{}: element {elem}'s index", case.name);
            }
            (got, want) => panic!(
                "{}: element {elem} expected {want:?}, got {:?}",
                case.name,
                got.map(|p| ext(p.rect)),
            ),
        }
    }
    // every stop a group declares is among the probes, or the table would not see it move
    for g in case.groups {
        let probed = case.places.iter().filter(|p| p.1 == Some(g.0)).count();
        assert!(g.1 <= probed, "{}: group {} has {} stops but only {probed} are probed", case.name, g.0, g.1);
    }
}

