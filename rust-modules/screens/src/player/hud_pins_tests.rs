//! **Characterization pins for the classic player HUD, written BEFORE it is split.**
//!
//! The HUD refactor that follows this commit (the `player_hud` split into state, model, motion
//! and geometry, `HudNav::focus` becoming a `GroupId`, and the Up/Down/OK arms of `PlayerScreen`
//! moving onto `FocusEngine` groups) is declared to change no behaviour. This module is how that
//! claim is checked: it records what the classic HUD does TODAY, as literal data, and the same
//! tables must pass unchanged after the split. A row that has to be edited is a behaviour change
//! and is reported as one; it is never "updated to match".
//!
//! **Driven through a real `Dispatcher`, not `Machine::step`.** After the refactor the control row
//! and the tabs answer Up/Down/OK with `Handled::No` and the ENGINE moves focus, arms the press
//! and commits it; a harness that called `step` directly would read that as a regression. So the
//! mounted `PlayerScreen` sits in a real `Dispatcher` with a rig that only records the player
//! requests, and every key is delivered the way the television delivers one: the app's per-key
//! preamble (`HudState::note_fresh_press`), a key-down frame, a frame with nothing in it (which is
//! what pins the Tick-time focus repair), the key-up a hold-free tap produces, and a run of
//! further frames long enough for a press the engine armed to commit. The ms of every frame is
//! chosen here, so a run is deterministic.
//!
//! **What a step observes** is only the screen's own state and what it asked for: the focus
//! region (`nav.focus`, as a number whatever its type), the row's button and the tab, whether the
//! key arrived on a visible transport, whether it was dismissed, whether the key RAISED the
//! transport's timer, and the `PlayerReq`s raised. The engine's own focus key is deliberately NOT
//! observed: today the screen's own Up and Down arms set `nav.focus` without telling the engine
//! (only the row's repair does), so the two can differ, and making them one value is the point
//! of the refactor. The timer's value is not observed either, only whether the key raised it:
//! once the engine owns OK the commit lands a few frames after the key-down, and the exact ms is
//! the one thing that legitimately moves.
//! No edge rule, group kind or `seat()` is pinned; those are the mechanism the refactor replaces,
//! and the sequences pin where focus actually lands.
//!
//! **A pin is a key string and the state after its last key**, replayed from a fresh page.
//! `U D L R K` are the five keys, `!` is the app pushing plain discs into the screen between two
//! presses. The tables were generated by exploring every state reachable from a hidden transport
//! (the first key of any walk only wakes it) and pinning all five keys from each, plus named
//! walks. A state is the focus region, the row's button while the row has focus, the tab, and
//! whether the transport is dismissed or still up; a walk that swaps the occupant with `!` is
//! pinned but not explored further (the plain discs it lands on have their own table). The flags
//! column reads `v` the key arrived on a visible transport, `r` the key raised the transport's
//! timer, `d` the transport is dismissed, `-` none of them.
//!
//! **The playhead is idle on purpose.** No duration is installed, so LEFT/RIGHT on the scrubber
//! raise the transport and move no target, and an OK there toggles play/pause. Installing one
//! would write a process global, and would make the pins depend on whether the refactor reads the
//! duration from the screen's own model or from the global. The tests assert the idle premise
//! before they start instead of assuming it. Every walk is at most [`DEEPEST`] presses so that
//! neither the transport's own timeout nor the Up Next countdown (10 s) is reached by the clock
//! this harness runs.
//!
//! **The geometry census** reads the screen through its `Focusable` impl with the fixture
//! measure, undrawn (a draw needs GL and a font, which the host suite cannot link): every group's
//! id, length and extent, and every probed element's group and placement, for each occupant of
//! the row, with and without chapters, and for a failed read-out, plus the overscan audit's rects.
//! Rects are compared to a thousandth of a pixel so an equivalent re-derivation of the same
//! constants cannot trip them.
//!
//! The pin tables and the census above name no appkit item but `slot_for`, `ControlSlot`, `Controls`,
//! `Busy` and `overscan_rects`, and no private method of the screen, so they compile against both sides of the
//! split. **The `sections` module at the end is the one exception**: PR8's Chapters and Info pages are the
//! screen's own state, so its tests name `Section`, `HudCommand` and the screen's `hud.sections`, and run the same
//! dispatcher with the rig performing a `toggle_section` the way the app's performer does.

