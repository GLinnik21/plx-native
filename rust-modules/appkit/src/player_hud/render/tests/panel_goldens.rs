fn run(text: &str, size: i32, ink: [f32; 4], bold: bool, align: i32, at: [f32; 4]) -> Run {
    Run { text: text.into(), size, ink, bold, align, at: rect(at), clip: None, fade: None, lead: None, label: false }
}

